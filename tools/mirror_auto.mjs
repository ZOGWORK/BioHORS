// Writes the BLUE copy of a RED Zenith auto with Zenith's own mirror (zenith-core mirrorAuto, the
// code behind the editor's mirror button), the way the field file declares the field symmetric
// (biobuzz.field.json: pointSymmetry). Waypoint references are written out as the mirrored numbers,
// and field ids (hiveRedUpCell, gardenRed2, ...) are swapped with the season's mirrorId hook.
//
// Usage, from the repo root:  node tools/mirror_auto.mjs [two-tip]
// Writes autos/<name>-blue.auto.json. Re-run it after every change to the RED auto or waypoints.json;
// ZenithAutoMatchTest fails if the BLUE file is not the mirror of the RED one.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { execSync } from "node:child_process";

const name = process.argv[2] ?? "two-tip";

// Where zenith-core is: ZENITH_NODE_MODULES if set, else this repo's node_modules (after `npm install`,
// which pins the CLI in package.json), else npx's cache (`npx zenith ...` without an install).
function zenithModules() {
    const has = (nm) => fs.existsSync(path.join(nm, "@horizon36596", "zenith-core"));
    if (process.env.ZENITH_NODE_MODULES) return process.env.ZENITH_NODE_MODULES;
    if (has("node_modules")) return "node_modules";
    let cache;
    try {
        cache = execSync("npm config get cache", { encoding: "utf8" }).trim();
    } catch {
        cache = process.platform === "win32"
            ? path.join(process.env.LOCALAPPDATA ?? os.homedir(), "npm-cache")
            : path.join(os.homedir(), ".npm");
    }
    const npx = path.join(cache, "_npx");
    for (const dir of fs.existsSync(npx) ? fs.readdirSync(npx) : []) {
        const nm = path.join(npx, dir, "node_modules");
        if (has(nm)) return nm;
    }
    throw new Error("zenith-core not found: run `npm install` in the repo, or set ZENITH_NODE_MODULES");
}

const nm = zenithModules();
const load = (pkg) => import(pathToFileURL(path.join(nm, "@horizon36596", pkg, "dist", "index.js")).href);
const core = await load("zenith-core");
const seasons = await load("zenith-seasons");

const read = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const red = read(path.join("autos", `${name}.auto.json`));
if (red.alliance !== "RED") throw new Error(`${name} is ${red.alliance}; mirror the RED auto`);
const field = read(red.field);
const waypoints = read("autos/waypoints.json");

const blue = core.mirrorAuto(red, core.mirrorForField(field), seasons.seasonFor(field).mirrorId, waypoints);
// A referenced waypoint comes back as bare numbers; carry its provenance across, so the BLUE poses
// stay labelled as what they are (the RED waypoint's label, mirrored).
function carryProvenance(r, b) {
    if (Array.isArray(r)) return r.forEach((x, i) => carryProvenance(x, b[i]));
    if (r === null || typeof r !== "object") return;
    if (typeof r.ref === "string" && b && b.provenance === undefined) {
        const label = (waypoints.waypoints[r.ref].provenance ?? "").split(":")[0] || "SET BY HAND";
        b.provenance = `${label}: the point mirror of waypoints.json ${r.ref} (see its provenance there)`;
        return;
    }
    for (const k of Object.keys(r)) carryProvenance(r[k], b?.[k]);
}
carryProvenance(red, blue);

blue.name = `${name}-blue`;
blue.title = `${red.title} (BLUE)`;
blue.description = `GENERATED by tools/mirror_auto.mjs from ${name}.auto.json with Zenith's mirror `
    + `(${core.mirrorForField(field)}); do not edit, edit the RED auto and re-run it. ` + red.description;

const out = path.join("autos", `${blue.name}.auto.json`);
fs.writeFileSync(out, JSON.stringify(blue, null, 2) + "\n");
console.log(`wrote ${out}`);
